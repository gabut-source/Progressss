-- Jalankan sekali di Supabase Dashboard > SQL Editor.
-- Buat user admin di Authentication > Users, lalu masukkan UUID-nya ke webgis_admins.

create table if not exists public.webgis_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.city_zones (
  city text primary key,
  geojson jsonb not null,
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.samples (
  id bigint generated by default as identity primary key,
  city text not null,
  zone text not null default '',
  sample_number text not null,
  ident text not null,
  surveyor text not null,
  sample_date date not null,
  longitude double precision,
  latitude double precision,
  zone_source text not null default 'attribute',
  properties jsonb not null default '{}'::jsonb,
  uploaded_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  constraint samples_unique_upload unique (city, sample_date, ident, zone)
);

create index if not exists samples_city_date_idx on public.samples (city, sample_date);
create index if not exists samples_city_zone_idx on public.samples (city, zone);

alter table public.webgis_admins enable row level security;
alter table public.city_zones enable row level security;
alter table public.samples enable row level security;

revoke all on public.webgis_admins from anon, authenticated;
grant select on public.webgis_admins to authenticated;
grant select on public.city_zones, public.samples to anon, authenticated;
grant insert, update, delete on public.city_zones, public.samples to authenticated;
grant usage, select on sequence public.samples_id_seq to authenticated;

drop policy if exists "admins_read_own_membership" on public.webgis_admins;
create policy "admins_read_own_membership" on public.webgis_admins
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "anyone_reads_city_zones" on public.city_zones;
create policy "anyone_reads_city_zones" on public.city_zones
  for select to anon, authenticated using (true);

drop policy if exists "admins_insert_city_zones" on public.city_zones;
create policy "admins_insert_city_zones" on public.city_zones
  for insert to authenticated with check (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

drop policy if exists "admins_update_city_zones" on public.city_zones;
create policy "admins_update_city_zones" on public.city_zones
  for update to authenticated using (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  ) with check (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

drop policy if exists "admins_delete_city_zones" on public.city_zones;
create policy "admins_delete_city_zones" on public.city_zones
  for delete to authenticated using (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

drop policy if exists "anyone_reads_samples" on public.samples;
create policy "anyone_reads_samples" on public.samples
  for select to anon, authenticated using (true);

drop policy if exists "admins_insert_samples" on public.samples;
create policy "admins_insert_samples" on public.samples
  for insert to authenticated with check (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

drop policy if exists "admins_update_samples" on public.samples;
create policy "admins_update_samples" on public.samples
  for update to authenticated using (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  ) with check (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

drop policy if exists "admins_delete_samples" on public.samples;
create policy "admins_delete_samples" on public.samples
  for delete to authenticated using (
    exists (select 1 from public.webgis_admins where user_id = (select auth.uid()))
  );

